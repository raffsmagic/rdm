/// Whether a character is a letter: Unicode's general category L.
pub(crate) fn is_letter(character: char) -> bool {
    if character.is_ascii() {
        return character.is_ascii_alphabetic();
    }
    // A letter, and not a number written with letters (a Roman numeral is alphabetic too).
    if !character.is_alphabetic() || character.is_numeric() {
        return false;
    }
    let point = character as u32;
    MARKS
        .binary_search_by(|&(first, last)| {
            if last < point {
                std::cmp::Ordering::Less
            } else if first > point {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_err()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_list_is_in_order_and_holds_nothing_it_need_not() {
        assert!(MARKS.iter().all(|(first, last)| first <= last));
        // In order, with a gap between each range and the next: two that touched would be one.
        assert!(MARKS.windows(2).all(|pair| pair[0].1 + 1 < pair[1].0));
        let listed: u32 = MARKS.iter().map(|(first, last)| last - first + 1).sum();
        assert_eq!(listed, 1510);
        // Every one is a character, and one that would have been counted without the list.
        for (first, last) in MARKS {
            for point in first..=last {
                let character = char::from_u32(point).expect("a character");
                assert!(character.is_alphabetic() && !character.is_numeric(), "U+{point:04X}");
                assert!(!is_letter(character), "U+{point:04X}");
            }
        }
    }

    #[test]
    fn letters_and_what_only_looks_like_one() {
        // Lu, Ll, Lt, Lm and Lo, from several scripts and planes.
        for letter in
            "aZ\u{e9}\u{df}\u{1c5}\u{2b0}\u{aa}\u{3b1}\u{416}\u{5d0}\u{628}\u{915}\u{e01}\u{3042}\u{754c}\u{d55c}\u{10400}\u{20000}".chars()
        {
            assert!(is_letter(letter), "U+{:04X}", letter as u32);
        }
        // Marks (Mn, Mc), enclosed letters (So), numbers (Nd, Nl, No), and the rest.
        let others =
            "\u{301}\u{345}\u{5b0}\u{64e}\u{93e}\u{94d}\u{e34}\u{24b6}\u{1f130}\u{2163}\u{3007}\u{661}\u{b2}7 _-\u{1f600}\u{1f1e9}\u{200d}";
        for other in others.chars() {
            assert!(!is_letter(other), "U+{:04X}", other as u32);
        }
    }

    #[test]
    fn every_other_alphabetic_character_is_a_letter() {
        // How many letters Unicode 17.0.0 has. A toolchain that knows a later Unicode knows
        // more of them, and then this count and the list above are both to be brought up to it.
        if char::UNICODE_VERSION == (17, 0, 0) {
            let letters = ('\0'..=char::MAX).filter(|character| is_letter(*character)).count();
            assert_eq!(letters, 145_672);
        }
    }
}
