//! What a letter is.
//!
//! The Go gateway counts the letters of a state with `unicode.IsLetter`: Unicode's general
//! category L, and nothing else. The standard library here has no test for a category. What
//! it has is `char::is_alphabetic`, the wider property Alphabetic, which is the letters and
//! with them the letter numbers (a Roman numeral) and the code points Unicode lists as
//! Other_Alphabetic: the signs that Devanagari, Thai, Arabic, Hebrew and many other scripts
//! write a vowel with, which are marks, and the circled and squared letters, which are
//! symbols. Counting those made a text in such a script look further from ASCII than the Go
//! gateway takes it to be, and could set a local backend aside for a state it would have kept.
//!
//! So the marks and symbols are listed here, and taken away. In Unicode 17.0.0, which is what
//! Rust 1.99 knows, the alphabetic characters that are not numbers and not in this list are
//! the letters exactly: all 145,672 of them, and no other.

